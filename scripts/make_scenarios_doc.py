def fmt_stop(s):
    h = s["hours"]
    conf = {"verified": "часы проверены (OSM/2GIS)", "estimate": "часы — оценка", "outdoor": "открытое место"}.get(h["confidence"], h["confidence"])
    return (f"| {s['arrive']}–{s['leave']} | **{s['name']}** ({s['category']}) | {s['why']} | {s['todo']} | {h['text']} · _{conf}_ |")


def run_swap():
    """Проверка кнопки «другое место»: заменить первую остановку, остальные оставить."""
    base = post({"text": SCENARIOS[0]["text"], "now": "17:20", "weather": "now"})
    st = stops(base)
    if not st:
        return None
    first, others = st[0], [s["id"] for s in st[1:]]
    alt = post({"text": "", "parsed": base["parsed"], "now": "17:20", "weather": "now", "exclude": [first["id"]], "keep": others})
    ast = stops(alt)
    ok = bool(ast) and first["id"] not in [s["id"] for s in ast] and all(o in [s["id"] for s in ast] for o in others) and on_time(alt)
    return first, ast, ok


