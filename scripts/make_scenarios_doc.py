def post(body):
    t = time.time()
    r = httpx.post(f"{API}/api/plan", json=body, timeout=120).json()
    r["_sec"] = round(time.time() - t, 1)
    return r


def stops(r):
    return [s for s in r.get("steps", []) if s["type"] == "stop"]


def mins(hhmm):
    h, m = map(int, hhmm.split(":"))
    return h * 60 + m


def on_time(r):
    if r.get("error"):
        return None
    a, d, n = mins(r["summary"]["arrive"]), mins(r["deadline"]), mins(r["now"])
    if a < n:
        a += 1440
    if d < n:
        d += 1440
    return a <= d


# ---------- проверки ----------
def chk_on_time(r):
    return ("Успевает к сроку (прибытие ≤ дедлайн)", on_time(r))


def chk_open(r):
    st = stops(r)
    return ("Каждое место открыто всё время визита", bool(st) and all(s["hours"]["status"] == "open" for s in st))


def chk_labels(r):
    st = stops(r)
    return ("У каждого места есть пометка надёжности часов и ссылка на источник (OSM / 2GIS / Википедия)",
            bool(st) and all(s["hours"]["confidence"] in ("verified", "estimate", "outdoor") and re.search(r"openstreetmap\.org|2gis\.kz|wikipedia\.org|wikidata\.org", s["source"]) for s in st))


def chk_why(r):
    st = stops(r)
    return ("У каждого места есть «почему» и «что делать»", bool(st) and all(len(s.get("why", "")) > 15 and len(s.get("todo", "")) > 10 for s in st))


def chk_stops_count(r):
    return ("1–3 конкретных места", 1 <= len(stops(r)) <= 3)


def chk_no_outdoor_cold(r):
    return ("В мороз нет уличных остановок", all(s["category"] not in OUTDOOR for s in stops(r)))


def chk_cold_leg(r):
    return ("В мороз на улице не больше 12 мин подряд", r.get("summary", {}).get("max_outdoor_leg", 99) <= 12)


def chk_loop(r):
    return ("Маршрут возвращает в точку старта", r.get("destination", {}).get("label", "").startswith("обратно"))


def chk_walk_only(r):
    return ("Прогулка — без такси", r.get("summary", {}).get("taxis", 1) == 0 and r["summary"]["walk_km"] >= 0.8)


def chk_kids(r):
    return ("Есть место для ребёнка", any(s["category"] in KIDS for s in stops(r)))


def chk_one_long(r):
    st = stops(r)
    return ("Одно место надолго (для работы)", len(st) == 1 and st[0]["stay"] >= 45)


def chk_sockets_honest(r):
    txt = " ".join(s.get("why", "") + " " + s.get("todo", "") for s in stops(r)).lower()
    return ("Честно говорит, что про розетки данных нет", "розет" in txt and bool(re.search(r"нет|не известн|уточн|спрос|провер", txt)))


def chk_night(r):
    return ("Ночью нет парков и площадок", all(s["category"] not in ("парк", "сад", "детская площадка") for s in stops(r)))


def chk_english(r):
    st = stops(r)
    return ("Ответ на языке запроса (английский)", bool(st) and all(not re.search(r"[а-яё]", s.get("why", "").lower()) for s in st))


def chk_airport(r):
    return ("Учитывает регистрацию: в аэропорту за 1,5 ч до вылета",
            any("1,5 часа" in n for n in (r.get("notes_original") or r.get("notes") or [])))


def chk_event(r):
    return ("Приходит на событие заранее (запас на вход)", any("лучше прийти" in n for n in (r.get("notes_original") or r.get("notes") or [])))


def chk_one_meal(r):
    return ("Не больше одной остановки «поесть»", sum(1 for s in stops(r) if s["category"] in ("ресторан", "фастфуд")) <= 1)


def chk_kazakh(r):
    st = stops(r)
    return ("Ответ на казахском", bool(st) and all(re.search(r"[әіңғүұқөһ]", (s.get("why", "") + s.get("todo", "")).lower()) for s in st))


def chk_closed_honest(r):
    notes = " ".join(r.get("notes_original") or r.get("notes") or [])
    return ("Честно: музеи сейчас закрыты — предлагает открытое", bool(re.search(r"закрыт|выходной", notes)) and not any(s["category"] == "музей" for s in stops(r)))


def chk_photo(r):
    ph = r.get("_photo") or {}
    return ("Фото узнано: Байтерек (Gemini Vision), старт маршрута — там",
            bool(ph.get("found")) and "Байтерек" in ph.get("label", "") and "Байтерек" in (r.get("origin") or {}).get("label", ""))


def chk_quiz(r):
    return ("В афише — квиз (городская афиша sxodim.com), по теме запроса",
            any(re.search(r"квиз|quiz", f"{e['title']} {e.get('kind', '')}", re.I) for e in r.get("events") or []))


def chk_exhibition(r):
    return ("Выставка, которая идёт сегодня и помещается в окно",
            any(re.search(r"выстав", f"{e['title']} {e.get('kind', '')}", re.I) and not e.get("later") for e in r.get("events") or []))


def chk_no_kids_event(r):
    return ("Детские события взрослому не предлагаются", all(not re.search(r"дет|утренник", f"{e['title']} {e.get('kind', '')}", re.I)
                                                          for e in r.get("events") or []))


def chk_meet(r):
    m = r.get("meet") or {}
    return ("Встреча посередине: разница в дороге ≤ 10 мин, у каждого — время выхода",
            bool(m) and abs(m["you_min"] - m["friend_min"]) <= 10 and any("выходить в" in n for n in (r.get("notes_original") or r.get("notes") or [])))


def chk_refusal(r):
    return ("Честный отказ с практическим советом", bool(r.get("error")) and bool(re.search(r"такси|просто иди|не успеть", r["error"])))


